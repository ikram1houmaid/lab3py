
a = 15
b = 4

# Addition
print(f"{a} + {b} = {a + b}")

# Soustraction
print(f"{a} - {b} = {a - b}")

# Multiplication
print(f"{a} * {b} = {a * b}")

# Division classique
print(f"{a} / {b} = {a / b}")

# Division entière
print(f"{a} // {b} = {a // b}")

# Modulo (reste)
print(f"{a} % {b} = {a % b}")

# Puissance
print(f"{a} ** {b} = {a ** b}")

# Puissance associative à droite
print("2 ** 3 ** 2 =", 2 ** 3 ** 2)
